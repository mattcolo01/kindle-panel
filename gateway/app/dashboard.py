"""Read a Lovelace dashboard and the data of its cards.

What is drawn is what the browser shows on a 600 px wide screen, without
interaction: the first view, its sections one below the other (below two
320 px columns the sections view has a single column, hui-sections-view.ts)
and, of the cards, only the ones in SUPPORTED_CARDS. Every other card is
skipped and logged.
"""

import logging
import re
from dataclasses import dataclass
from datetime import date

from .config import ENTITY_ID_RE
from .home_tasks import TaskColumn, column_view, text
from .ha_ws import HAWebSocket

log = logging.getLogger(__name__)

TASKS_CARD = "custom:home-tasks-card"
SUPPORTED_CARDS = ("heading", TASKS_CARD)

# Home Tasks list ids are config entry ids (ULIDs); its WS API takes 1-40 chars.
LIST_ID_RE = re.compile(r"^[0-9A-Za-z]{1,40}$")
MAX_CARDS = 50
MAX_COLUMNS = 10
MAX_PERSONS = 50


class DashboardError(Exception):
    """The dashboard cannot be drawn (missing, generated by a strategy, ...)."""


@dataclass(frozen=True)
class Heading:
    text: str
    subtitle: bool


@dataclass(frozen=True)
class TasksColumnSpec:
    list_id: str | None  # None: the card picks the first list
    options: dict


@dataclass(frozen=True)
class TasksCardSpec:
    title: str | None
    columns: tuple[TasksColumnSpec, ...]
    has_source: bool  # some column, drawn or not, names a list or an entity


@dataclass(frozen=True)
class TasksCard:
    title: str | None
    columns: tuple[TaskColumn, ...]


@dataclass(frozen=True)
class DashboardView:
    blocks: tuple[Heading | TasksCard, ...]
    battery: int | None  # percent, multiple of 5


def first_view_cards(config: object) -> list:
    if not isinstance(config, dict):
        raise DashboardError("the dashboard configuration is not a mapping")
    if "strategy" in config:
        raise DashboardError("dashboards generated by a strategy exist only in the browser")
    views = config.get("views")
    if not isinstance(views, list) or not views or not isinstance(views[0], dict):
        raise DashboardError("the dashboard has no views")
    view = views[0]
    if "strategy" in view:
        raise DashboardError("views generated by a strategy exist only in the browser")
    if isinstance(view.get("sections"), list):
        cards = []
        for section in view["sections"]:
            if isinstance(section, dict) and isinstance(section.get("cards"), list):
                cards.extend(section["cards"])
        return cards
    return view.get("cards") if isinstance(view.get("cards"), list) else []


def parse_tasks_card(card: dict) -> TasksCardSpec | None:
    """setConfig of the card: a single-list config becomes one column."""
    columns = card.get("columns")
    if card.get("list_id") and not columns:
        columns = [{k: v for k, v in card.items() if k not in ("type", "columns")}]
    if not isinstance(columns, list) or not columns:
        columns = [{}]
    specs = []
    has_source = any(isinstance(c, dict) and (c.get("list_id") or c.get("entity_id")) for c in columns)
    for col in columns[:MAX_COLUMNS]:
        if not isinstance(col, dict):
            continue
        col = {k: v for k, v in col.items() if k != "type"}
        if col.get("entity_id"):
            log.info("Skipping a %s column on an external list (not supported)", TASKS_CARD)
            continue
        list_id = col.get("list_id")
        if list_id is not None and (not isinstance(list_id, str) or not LIST_ID_RE.match(list_id)):
            log.warning("Skipping a %s column with an invalid list_id", TASKS_CARD)
            continue
        specs.append(TasksColumnSpec(list_id or None, col))
    if not specs:
        return None
    title = card.get("title") if len(columns) > 1 and isinstance(card.get("title"), str) else None
    return TasksCardSpec(text(title) or None, tuple(specs), has_source)


def parse_dashboard(config: object) -> list[Heading | TasksCardSpec]:
    blocks: list[Heading | TasksCardSpec] = []
    skipped = []
    for card in first_view_cards(config)[:MAX_CARDS]:
        card_type = card.get("type") if isinstance(card, dict) else None
        if card_type == "heading":
            if isinstance(card.get("heading"), str) and card["heading"]:
                blocks.append(Heading(text(card["heading"]), card.get("heading_style") == "subtitle"))
        elif card_type == TASKS_CARD:
            spec = parse_tasks_card(card)
            if spec is not None:
                blocks.append(spec)
        else:
            skipped.append(text(card_type) or "?")
    if skipped:
        log.info("Skipping unsupported cards: %s", ", ".join(sorted(set(skipped))))
    return blocks


def as_dicts(value: object) -> list[dict]:
    return [item for item in value if isinstance(item, dict)] if isinstance(value, list) else []


@dataclass(frozen=True)
class DashboardData:
    blocks: tuple[Heading | TasksCardSpec, ...]  # list ids all resolved
    list_names: dict[str, str]
    tasks: dict[str, tuple[list[dict], list[dict]]]  # list id -> (tasks, sections)


async def fetch_dashboard(ws: HAWebSocket, url_path: str) -> DashboardData:
    """Raises HACommandError when HA refuses a command, DashboardError when
    the dashboard cannot be drawn."""
    blocks = parse_dashboard(await ws.command("lovelace/config", url_path=url_path))
    names: dict[str, str] = {}
    tasks: dict[str, tuple[list[dict], list[dict]]] = {}
    if not any(isinstance(b, TasksCardSpec) for b in blocks):
        return DashboardData(tuple(blocks), names, tasks)

    result = await ws.command("home_tasks/get_lists")
    lists = as_dicts(result.get("lists") if isinstance(result, dict) else None)
    for item in lists:
        if isinstance(item.get("id"), str):
            names[item["id"]] = text(item.get("name")) or item["id"]

    resolved: list[Heading | TasksCardSpec] = []
    for block in blocks:
        if isinstance(block, TasksCardSpec) and not block.has_source:
            # _loadLists: with no list configured the card shows the first one
            if not names:
                raise DashboardError("the Home Tasks card has no list and Home Tasks has none")
            first = next(iter(names))
            block = TasksCardSpec(block.title, (TasksColumnSpec(first, block.columns[0].options),)
                                  + block.columns[1:], True)
        resolved.append(block)

    for block in resolved:
        if not isinstance(block, TasksCardSpec):
            continue
        for col in block.columns:
            if col.list_id is None or col.list_id in tasks:
                continue
            if col.list_id not in names:
                raise DashboardError(f"Home Tasks has no list {col.list_id}")
            result = await ws.command("home_tasks/get_tasks", list_id=col.list_id)
            if not isinstance(result, dict):
                result = {}
            tasks[col.list_id] = (as_dicts(result.get("tasks")), as_dicts(result.get("sections")))
    return DashboardData(tuple(resolved), names, tasks)


def assigned_persons(data: DashboardData) -> list[str]:
    """person.* entities assigned to tasks: their names come from HA states."""
    persons = []
    for task_list, _ in data.tasks.values():
        for task in task_list:
            person = task.get("assigned_person")
            if isinstance(person, str) and person.startswith("person.") and ENTITY_ID_RE.match(person) \
                    and person not in persons:
                persons.append(person)
    return persons[:MAX_PERSONS]


def person_names(states: dict[str, dict | None]) -> dict[str, str]:
    names = {}
    for entity_id, state in states.items():
        if state is None:
            continue
        attributes = state.get("attributes") if isinstance(state.get("attributes"), dict) else {}
        names[entity_id] = text(attributes.get("friendly_name")) or entity_id
    return names


def build_view(
    data: DashboardData,
    persons: dict[str, str],
    language: str,
    today: date,
    battery: int | None,
) -> DashboardView:
    blocks: list[Heading | TasksCard] = []
    for block in data.blocks:
        if isinstance(block, Heading):
            blocks.append(block)
            continue
        columns = []
        for col in block.columns:
            # A column without a list stays empty, as in the card
            task_list, sections = data.tasks.get(col.list_id, ([], [])) if col.list_id else ([], [])
            columns.append(column_view(col.options, data.list_names.get(col.list_id), task_list, sections,
                                       persons, language, today))
        blocks.append(TasksCard(block.title, tuple(columns)))
    return DashboardView(tuple(blocks), battery)
